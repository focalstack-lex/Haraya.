/** Standard 07:00 to 22:00 week used by most city cafes. */
function standardHours(open = '07:00', close = '22:00'): WeeklyHours {
  const day = { open, close };
  return { Monday: day, Tuesday: day, Wednesday: day, Thursday: day, Friday: day, Saturday: day, Sunday: day };
}

function lateNightHours(): WeeklyHours {
  const weekday = { open: '08:00', close: '23:00' };
  return {
    Monday: weekday,
    Tuesday: weekday,
    Wednesday: weekday,
    Thursday: weekday,
    Friday: { open: '08:00', close: '01:00' },
    Saturday: { open: '09:00', close: '01:00' },
    Sunday: { open: '09:00', close: '22:00' },
  };
}

function highlandHours(): WeeklyHours {
  const day = { open: '08:00', close: '18:00' };
  return { Monday: { open: null, close: null }, Tuesday: day, Wednesday: day, Thursday: day, Friday: day, Saturday: day, Sunday: day };
}

