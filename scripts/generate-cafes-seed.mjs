/**
 * Writes the SQL that stores the catalog spots in the database: Green Coffee and the Digos City shops, with their
 * hours and photo paths. The data lives in src/data (spots.ts, digosCafes.ts); this reads it and emits an idempotent
 * upsert, so nothing is retyped by hand. Re-run after changing that data, then run the file in the Supabase SQL
 * Editor (or `supabase db push`).
 *
 *   node scripts/generate-cafes-seed.mjs
 *
 * Needs Node 22.18 or newer (it imports the TypeScript data files directly).
 */
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const { CURATED_CAFES } = await import(pathToFileURL(resolve(root, 'src/data/spots.ts')).href);
const { DIGOS_CAFES } = await import(pathToFileURL(resolve(root, 'src/data/digosCafes.ts')).href);
const cafes = [...CURATED_CAFES, ...DIGOS_CAFES];

const text = (value) => `'${String(value).replaceAll("'", "''")}'`;
const list = (values) => (values.length === 0 ? `'{}'::text[]` : `array[${values.map(text).join(', ')}]::text[]`);
const json = (value) => `${text(JSON.stringify(value))}::jsonb`;

const rows = cafes.map((c) =>
  `  (${[
    text(c.id), text(c.handle), text(c.name), c.isRoastery ? 'true' : 'false', text(c.city), text(c.district), text(c.address),
    c.lat, c.lng, list(c.images), text(c.logoUrl), text(c.description), text(c.signature), json(c.menu), list(c.amenities),
    c.wifiMbps, list(c.brewMethods), c.priceLevel, json(c.hours), list(c.vibeTags), c.verified ? 'true' : 'false',
  ].join(', ')})`,
);

const columns = 'id, handle, name, is_roastery, city, district, address, lat, lng, images, logo_url, description, signature, menu, amenities, wifi_mbps, brew_methods, price_level, hours, vibe_tags, verified';
const updates = columns.split(', ').filter((name) => !['id', 'verified'].includes(name)).map((name) => `${name} = excluded.${name}`);

const sql = `-- Catalog spots stored in the database: Green Coffee and the Digos City coffee shops, with their hours and photo
-- paths (the photo files are served by the site from /spots/). Generated by scripts/generate-cafes-seed.mjs from
-- src/data; do not edit by hand, change the data and regenerate.
--
-- Safe to run more than once: rows are upserted by id. Visitor-driven counts (save_count, view_count) and the admin's
-- verified flag are never overwritten. The ids match the ones the app already used, so saved spots keep working.

-- 1. A spot can have no price listed (0); the app then shows no price and never calls the spot cheap.
alter table public.cafes drop constraint if exists cafes_price_level_check;
alter table public.cafes add constraint cafes_price_level_check check (price_level between 0 and 3);

-- 2. The spots.
insert into public.cafes (${columns})
values
${rows.join(',\n')}
on conflict (id) do update set
  ${updates.join(',\n  ')};

-- Check: this should return ${cafes.length}
-- select count(*) from public.cafes where id like 'osm-%' or id like 'digos-%' or id like 'curated-%';
`;

const out = resolve(root, 'supabase/migrations/20260929040000_seed_catalog_cafes.sql');
writeFileSync(out, sql, 'utf8');
console.log(`${cafes.length} spots written to ${out.replace(root, '.').replaceAll(String.fromCharCode(92), '/')}`);
